// Builds rules/lab-code-info.json from the NHS England / TRUD "PCD Refset Content" text files
// (PCD_Refset_Content_text_files.zip -> <date>_PCD_Refset_Content.txt).
//
// Usage:  node scripts/build-lab-code-info.js <folder containing the unzipped PCD txt files> [<date prefix, default latest>]
//
// What it derives (NOT hand-typed — QOF status comes from cluster membership):
//   qofClusters  every cluster whose Service_and_Ruleset lists a "QOF <ruleset>" service (e.g. IFCCHBAM_COD = QOF Diabetes;
//                DCCTHBA1C_COD is PHSMI only, so it is NOT a QOF cluster)
//   codes        for every concept in a cluster the lab catalogue's results reference (their `refsets`), its SNOMED
//                description and the clusters it belongs to — so a code that was learned from a report without its refsets
//                can still be shown with its description and QOF status.
// Extend the set of clusters by adding them to a result's `refsets` in rules/lab-catalogue.json and re-running.

'use strict';
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-lab-code-info.js <folder of unzipped PCD txt files> [date-prefix]');
  process.exit(2);
}
const files = fs
  .readdirSync(dir)
  .filter((f) => /_PCD_Refset_Content\.txt$/.test(f))
  .sort();
if (!files.length) {
  console.error('no *_PCD_Refset_Content.txt in ' + dir);
  process.exit(2);
}
const want = process.argv[3];
const file = want ? files.find((f) => f.startsWith(want)) : files[files.length - 1];
if (!file) {
  console.error('no PCD file with prefix ' + want);
  process.exit(2);
}
const release = file.slice(0, 8);

const catalogue = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'rules', 'lab-catalogue.json'), 'utf8'));
const seed = new Set();
for (const r of catalogue.results) for (const c of r.codes || []) for (const x of c.refsets || []) seed.add(x);

const rows = fs
  .readFileSync(path.join(dir, file), 'utf8')
  .split(/\r?\n/)
  .slice(1)
  .filter(Boolean)
  .map((l) => l.split('\t'));
// Cluster_ID, Cluster_description, SNOMED_code, SNOMED_code_description, PCD Refset ID, Service_and_Ruleset
const decode = (s) => String(s || '').replace(/&amp;/g, '&');
const qofClusters = new Set();
const codes = {};
for (const [cluster, , concept, description, , service] of rows) {
  if (
    String(service || '')
      .split('|')
      .some((x) => /^QOF /.test(x.trim()))
  )
    qofClusters.add(cluster);
  if (seed.has(cluster)) {
    const e = (codes[concept] = codes[concept] || { d: decode(description), c: [] });
    if (!e.c.includes(cluster)) e.c.push(cluster);
  }
}
for (const e of Object.values(codes)) e.c.sort();
// Codes the PCD files do not list (a lab-only code): take the description the LAB sends for it in the structure-only
// report fixtures, so every shipped code has a readable name.
const known = new Set();
for (const r of catalogue.results) for (const c of r.codes || []) known.add(c.conceptId);
const fixDir = path.join(__dirname, '..', 'fixtures', 'lab-catalogue');
if (fs.existsSync(fixDir)) {
  for (const f of fs.readdirSync(fixDir).filter((x) => /^report-.*.json$/.test(x))) {
    const fx = JSON.parse(fs.readFileSync(path.join(fixDir, f), 'utf8'));
    for (const g of [...(fx.investigationGroups || []), { results: fx.ungroupedResults || [] }])
      for (const r of g.results || []) {
        const rc = r.resultCode;
        if (rc && known.has(String(rc.conceptId)) && !codes[String(rc.conceptId)] && rc.description)
          codes[String(rc.conceptId)] = { d: rc.description, c: [] };
      }
  }
}
const out = {
  source: `NHS England / TRUD PCD refset content ${release}`,
  note: 'Generated by scripts/build-lab-code-info.js — do not edit by hand. qofClusters: clusters used by a QOF ruleset. codes: description + clusters for the concepts in the clusters the lab catalogue references.',
  qofClusters: [...qofClusters].sort(),
  codes: Object.fromEntries(Object.entries(codes).sort((a, b) => a[0].localeCompare(b[0]))),
};
fs.writeFileSync(path.join(__dirname, '..', 'rules', 'lab-code-info.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`${release}: ${out.qofClusters.length} QOF clusters, ${Object.keys(out.codes).length} concepts described`);
