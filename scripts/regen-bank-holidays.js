#!/usr/bin/env node
// Medicus Suite — refresh the English / UK bank-holiday calendar.
//
// Source of truth: GOV.UK https://www.gov.uk/bank-holidays.json
// Writes:
//   1. rules/uk-bank-holidays.json          (canonical GOV.UK-shaped dump)
//   2. shared/uk-bank-holidays-data.js      (embedded ESM export for sync use)
//   3. rota/shared/model.js bankHolidays    (DEFAULT_SETTINGS seed, E&W only)
//
// Usage:
//   node scripts/regen-bank-holidays.js                 # fetch + write
//   node scripts/regen-bank-holidays.js --check          # verify sync / horizon
//   node scripts/regen-bank-holidays.js --from-file FILE # write from local JSON
//
// No runtime fetch in the extension — clinical surfaces must not depend on
// www.gov.uk being reachable. Refresh on each build / when CI horizon fails.

'use strict';

const fs = require('fs');
const path = require('path');
const https = require('https');
const { pathToFileURL } = require('url');

const ROOT = path.join(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'rules', 'uk-bank-holidays.json');
const DATA_JS_PATH = path.join(ROOT, 'shared', 'uk-bank-holidays-data.js');
const MODEL_PATH = path.join(ROOT, 'rota', 'shared', 'model.js');
const SOURCE_URL = 'https://www.gov.uk/bank-holidays.json';
const DIVISIONS = ['england-and-wales', 'scotland', 'northern-ireland'];
/** CI / --check fails when the furthest E&W date is under this many months out. */
const MIN_HORIZON_MONTHS = 9;

const check = process.argv.includes('--check');
const fromFileIdx = process.argv.indexOf('--from-file');
const fromFile = fromFileIdx >= 0 ? process.argv[fromFileIdx + 1] : null;

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(
        url,
        { headers: { Accept: 'application/json', 'User-Agent': 'medicus-suite-regen-bank-holidays' } },
        (res) => {
          if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
            fetchJson(res.headers.location).then(resolve, reject);
            return;
          }
          if (res.statusCode !== 200) {
            reject(new Error(`GET ${url} → ${res.statusCode}`));
            res.resume();
            return;
          }
          const chunks = [];
          res.on('data', (c) => chunks.push(c));
          res.on('end', () => {
            try {
              resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')));
            } catch (e) {
              reject(e);
            }
          });
        }
      )
      .on('error', reject);
  });
}

function validatePayload(data) {
  if (!data || typeof data !== 'object') throw new Error('payload is not an object');
  for (const div of DIVISIONS) {
    if (!data[div] || !Array.isArray(data[div].events)) {
      throw new Error(`missing division events: ${div}`);
    }
    for (const ev of data[div].events) {
      if (!ev || typeof ev.date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(ev.date)) {
        throw new Error(`bad event date in ${div}: ${JSON.stringify(ev)}`);
      }
    }
  }
}

function horizonISO(data, division = 'england-and-wales') {
  const dates = data[division].events.map((e) => e.date).sort();
  return dates[dates.length - 1];
}

function monthsUntil(iso) {
  const now = new Date();
  const target = new Date(iso + 'T12:00:00');
  return (target.getFullYear() - now.getFullYear()) * 12 + (target.getMonth() - now.getMonth());
}

/** Default Rota seed: current calendar year through the E&W horizon (inclusive). */
function defaultEwDates(data) {
  const year = new Date().getFullYear();
  const from = `${year}-01-01`;
  return data['england-and-wales'].events
    .map((e) => e.date)
    .filter((d) => d >= from)
    .sort();
}

function buildDataJs(data, fetchedAt) {
  const divisions = {};
  for (const div of DIVISIONS) {
    divisions[div] = {
      division: data[div].division || div,
      events: data[div].events.map((e) => ({
        title: e.title || '',
        date: e.date,
        notes: e.notes || '',
      })),
    };
  }
  const meta = {
    source: SOURCE_URL,
    fetchedAt,
    horizon: { 'england-and-wales': horizonISO(data) },
  };
  return (
    '// © 2026 Graysbrook Ltd. Proprietary — all rights reserved. See LICENSE.\n' +
    '// GENERATED by scripts/regen-bank-holidays.js — do not edit by hand.\n' +
    '// Source: ' +
    SOURCE_URL +
    '\n' +
    "'use strict';\n\n" +
    'export const UK_BANK_HOLIDAYS_META = ' +
    JSON.stringify(meta, null, 2) +
    ';\n\n' +
    'export const UK_BANK_HOLIDAYS = ' +
    JSON.stringify(divisions, null, 2) +
    ';\n'
  );
}

function extractBankHolidayDatesFromModel(modelSrc) {
  const startMarker = 'bankHolidays: [';
  const start = modelSrc.indexOf(startMarker);
  if (start < 0) return null;
  const arrayStart = modelSrc.indexOf('[', start);
  let i = arrayStart + 1;
  let depth = 1;
  while (i < modelSrc.length && depth > 0) {
    if (modelSrc[i] === '[') depth++;
    else if (modelSrc[i] === ']') depth--;
    i++;
  }
  const body = modelSrc.slice(arrayStart, i);
  return [...body.matchAll(/'(\d{4}-\d{2}-\d{2})'/g)].map((m) => m[1]);
}

function patchModelBankHolidays(modelSrc, dates) {
  const commentNeedle = '  // England & Wales bank holidays';
  const commentStart = modelSrc.indexOf(commentNeedle);
  if (commentStart < 0) throw new Error('bankHolidays comment not found in rota/shared/model.js');
  const arrayStart = modelSrc.indexOf('bankHolidays: [', commentStart);
  if (arrayStart < 0) throw new Error('bankHolidays array not found in rota/shared/model.js');
  const bracket = modelSrc.indexOf('[', arrayStart);
  let i = bracket + 1;
  let depth = 1;
  while (i < modelSrc.length && depth > 0) {
    if (modelSrc[i] === '[') depth++;
    else if (modelSrc[i] === ']') depth--;
    i++;
  }
  if (depth !== 0) throw new Error('unbalanced bankHolidays array in model.js');
  const body = dates.map((d) => `    '${d}',`).join('\n');
  const replacement =
    '  // England & Wales bank holidays (editable in Settings).\n' +
    '  // Seeded from rules/uk-bank-holidays.json by scripts/regen-bank-holidays.js.\n' +
    '  bankHolidays: [\n' +
    body +
    '\n  ]';
  return modelSrc.slice(0, commentStart) + replacement + modelSrc.slice(i);
}

function datesKey(events) {
  return events.map((e) => e.date).join(',');
}

async function runCheck(data) {
  const problems = [];
  const horizon = horizonISO(data);
  const months = monthsUntil(horizon);
  if (months < MIN_HORIZON_MONTHS) {
    problems.push(
      `england-and-wales horizon ${horizon} is only ~${months} months out ` +
        `(need ≥ ${MIN_HORIZON_MONTHS}). Run: node scripts/regen-bank-holidays.js`
    );
  }
  if (!fs.existsSync(DATA_JS_PATH)) {
    problems.push('shared/uk-bank-holidays-data.js missing — run regen');
  } else {
    const mod = await import(pathToFileURL(DATA_JS_PATH).href);
    for (const div of DIVISIONS) {
      const have = datesKey(mod.UK_BANK_HOLIDAYS[div]?.events || []);
      const expect = datesKey(data[div].events);
      if (have !== expect) problems.push(`embedded data drift for ${div}`);
    }
  }
  const modelSrc = fs.readFileSync(MODEL_PATH, 'utf8');
  const modelDates = extractBankHolidayDatesFromModel(modelSrc);
  const expectDates = defaultEwDates(data);
  if (!modelDates) {
    problems.push('could not parse bankHolidays from rota/shared/model.js');
  } else if (modelDates.join(',') !== expectDates.join(',')) {
    problems.push(
      `rota DEFAULT_SETTINGS.bankHolidays out of sync (have ${modelDates.length}, expect ${expectDates.length})`
    );
  }
  if (problems.length) {
    console.error('Bank holidays OUT OF SYNC / STALE:\n  - ' + problems.join('\n  - '));
    process.exit(1);
  }
  console.log(`Bank holidays OK (E&W horizon ${horizon}, ~${months} months; Rota seed ${expectDates.length} dates).`);
}

async function main() {
  let data;
  let fetchedAt;
  if (fromFile) {
    data = JSON.parse(fs.readFileSync(fromFile, 'utf8'));
    fetchedAt = new Date().toISOString().slice(0, 10);
  } else if (check) {
    data = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
    validatePayload(data);
    await runCheck(data);
    return;
  } else {
    data = await fetchJson(SOURCE_URL);
    fetchedAt = new Date().toISOString().slice(0, 10);
  }
  validatePayload(data);

  const horizon = horizonISO(data);
  const months = monthsUntil(horizon);
  const ewDates = defaultEwDates(data);

  if (months < MIN_HORIZON_MONTHS) {
    console.warn(`Warning: E&W horizon ${horizon} is only ~${months} months out (want ≥ ${MIN_HORIZON_MONTHS}).`);
  }

  fs.writeFileSync(JSON_PATH, JSON.stringify(data, null, 2) + '\n');
  fs.writeFileSync(DATA_JS_PATH, buildDataJs(data, fetchedAt));
  const modelSrc = fs.readFileSync(MODEL_PATH, 'utf8');
  fs.writeFileSync(MODEL_PATH, patchModelBankHolidays(modelSrc, ewDates));

  console.log(
    `Wrote rules/uk-bank-holidays.json, shared/uk-bank-holidays-data.js, ` +
      `and Rota seed (${ewDates.length} E&W dates ${ewDates[0]} → ${ewDates[ewDates.length - 1]}; horizon ${horizon}).`
  );
}

main().catch((err) => {
  console.error(err.stack || err);
  process.exit(1);
});
